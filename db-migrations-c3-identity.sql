-- Function bodies are the bounded deploy mirror of current schema.sql; the checked-in
-- inspect-1939-v50-c3-identity-deploy.sql serializer enforces byte-exact endpoint parity.

DO $relation_identity_default$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='relation' AND column_name='id'
      AND data_type='bigint' AND is_identity='NO'
  ) THEN
    ALTER TABLE public.relation
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(
      pg_get_serial_sequence('public.relation','id'),
      (SELECT coalesce(max(id),0)+1 FROM public.relation), false
    );
  END IF;
END $relation_identity_default$;

